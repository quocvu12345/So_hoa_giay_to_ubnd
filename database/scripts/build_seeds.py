#!/usr/bin/env python3
"""Build reproducible SQL from the local catalogue and curated public metadata.

No network requests, no execution of JS, no guessed official case ownership.
Run: python3 database/scripts/build_seeds.py [--check]
"""
import argparse
import hashlib
import json
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT.parent
NAMESPACE = uuid.UUID('d15116a0-77fa-49ac-a626-f623414a170f')


def ident(key):
    return str(uuid.uuid5(NAMESPACE, key))


def sql(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return sql(json.dumps(value, ensure_ascii=False)) + '::jsonb'
    return "'" + str(value).replace("'", "''") + "'"


def insert(table, columns, rows):
    if not rows:
        return ''
    return f"INSERT INTO {table} ({','.join(columns)}) VALUES\n" + ',\n'.join(
        '(' + ','.join(map(sql, row)) + ')' for row in rows
    ) + '\nON CONFLICT DO NOTHING;\n\n'


def js_array(name, text):
    tail = text.split('window.' + name + ' =', 1)[1].lstrip()
    return json.JSONDecoder().raw_decode(tail)[0]


def generate():
    text = (PROJECT / 'assets/danh-muc-ho-so.js').read_text()
    departments = js_array('HOSO_DEPARTMENTS', text)
    groups = js_array('HOSO_CATALOG', text)
    records = json.loads((ROOT / 'data/public_documents.json').read_text())['records']
    org = lambda group: 'tl-ubnd' if group == 'UBND' else 'tl-hdnd'
    header = '-- Generated by scripts/build_seeds.py. Do not edit generated rows.\nSET search_path = hoso, pg_catalog;\nSET standard_conforming_strings = on;\n\n'
    catalog = header + '-- Catalogue and organizational assignments are PROPOSED, not an approved inventory.\n'
    catalog += insert('organizations', ['code', 'name', 'kind', 'locality'], [
        ['tl-ubnd', 'Ủy ban nhân dân phường Từ Liêm', 'UBND', 'Phường Từ Liêm, thành phố Hà Nội'],
        ['tl-hdnd', 'Hội đồng nhân dân phường Từ Liêm', 'HDND', 'Phường Từ Liêm, thành phố Hà Nội']])
    catalog += insert('departments', ['code', 'name', 'kind', 'assignment_note'], [
        [d['id'], d['name'], d['kind'], d['assignment']] for d in departments])
    scopes = sorted({(g['owner'], org(g['group'])) for g in groups} | {('vp', 'tl-hdnd')})
    catalog += insert('department_scopes', ['department_code', 'organization_code'], scopes)
    catalog += insert('work_groups', ['code', 'organization_code', 'department_code', 'title', 'responsibility', 'filing_rule', 'business_fields'], [
        [g['code'], org(g['group']), g['owner'], g['title'], g['responsibility'], g['filingRule'], g['businessFields']] for g in groups])
    catalog += insert('document_types', ['code', 'work_group_code', 'name'], [
        [t['id'], g['code'], t['name']] for g in groups for t in g['documentTypes']])
    catalog += insert('field_definitions', ['code', 'document_type_code', 'label', 'position'], [
        [f"{t['id']}-F{i:02}", t['id'], label, i] for g in groups for t in g['documentTypes'] for i, label in enumerate(t['fields'], 1)])
    catalog += insert('roles', ['code', 'name', 'scope_kind'], [
        ['employee', 'Chuyên viên', 'assigned'], ['clerk', 'Văn thư / lưu trữ', 'organization'],
        ['manager', 'Trưởng phòng / Trưởng Ban / phụ trách đơn vị', 'department'],
        ['chair', 'Chủ tịch UBND', 'organization'], ['council', 'Lãnh đạo HĐND', 'organization'],
        ['technical_admin', 'Quản trị kỹ thuật', 'technical']])
    role_actions = {
        'employee': ['read', 'prepare', 'submit'], 'clerk': ['read', 'prepare', 'submit', 'archive', 'return'],
        'manager': ['read', 'assign', 'accept', 'escalate', 'return'],
        'chair': ['read', 'decide', 'return'], 'council': ['read', 'decide', 'return'],
        'technical_admin': ['configure']}
    catalog += insert('permissions', ['code', 'description'], [[f'dossier.{a}', f'Thao tác {a} trong phạm vi phân công'] for a in sorted({a for actions in role_actions.values() for a in actions})])
    catalog += insert('role_permissions', ['role_code', 'permission_code'], [[r, 'dossier.' + a] for r, actions in role_actions.items() for a in actions])
    catalog += insert('workflow_states', ['code', 'label'], [
        ['draft', 'Đang chuẩn bị'], ['returned', 'Yêu cầu bổ sung'], ['department_review', 'Chờ trưởng phòng / Ban'],
        ['leadership_review', 'Chờ lãnh đạo cho ý kiến'], ['ready_archive', 'Chờ tiếp nhận nộp lưu'], ['archived', 'Đã lưu trữ']])
    transitions = []
    for state in ['draft', 'returned']:
        for role in ['employee', 'clerk']:
            transitions.append([state, 'submit', role, 'department_review', True, False])
    transitions += [
        ['department_review', 'accept', 'manager', 'ready_archive', True, False],
        ['department_review', 'escalate', 'manager', 'leadership_review', True, True],
        ['department_review', 'return', 'manager', 'returned', False, True],
        ['ready_archive', 'archive', 'clerk', 'archived', True, False],
        ['ready_archive', 'return', 'clerk', 'returned', False, True]]
    for role in ['chair', 'council']:
        transitions += [['leadership_review', 'decide', role, 'ready_archive', True, True], ['leadership_review', 'return', role, 'department_review', False, True]]
    catalog += insert('workflow_transitions', ['from_state', 'action', 'actor_role', 'to_state', 'requires_verified_documents', 'requires_note'], transitions)

    public = header + '-- Real public metadata. No real internal dossier, assignee, receipt date or workflow status is invented.\n'
    source_rows, doc_rows, file_rows, classification_rows, manifest = [], [], [], [], []
    for r in records:
        source = r['source']; doc_id = ident(r['id']); source_id = 'source-' + r['id']
        source_rows.append([source_id, source['publisher'], source['url'], source['resolved_url'], source['retrieved_at'], source['response_sha256'], r['verification_note']])
        doc_rows.append([doc_id, r['id'], 'public_source', r['title'], r['document_form'], r['document_number'], r['issued_on'], r['published_at'], r['issuer_code'], r['issuer_name'], source_id, r['metadata_status'], r['verification_note'], r['source_observations']])
        classification_rows.append([doc_id, r['suggested_work_group'], 'proposed', 'Gợi ý tra cứu theo nội dung công khai; không xác nhận phòng chủ trì hoặc mã hồ sơ nội bộ thực tế.'])
        for i, f in enumerate([r['file']] + r.get('extra_files', []), 1):
            component_key = 'main' if i == 1 else f'attachment-{i-1}'
            file_rows.append([ident(r['id'] + f':file:{i}'), doc_id, component_key, 1, f['role'], f['original_name'], f['media_type'], f['byte_size'], f['sha256'], f['page_count'], f['resolved_url'], f['local_path'], source['retrieved_at']])
            if f['local_path']:
                assert hashlib.sha256((ROOT / f['local_path']).read_bytes()).hexdigest() == f['sha256']
            manifest.append({'document_key': r['id'], 'file_id': ident(r['id'] + f':file:{i}'), 'component_key': component_key, 'version_no': 1,
                'url': f['resolved_url'], 'filename': f"{r['id']}-{i}." + ('pdf' if f['media_type'] == 'application/pdf' else 'xlsx'),
                'sha256': f['sha256'], 'byte_size': f['byte_size'], 'page_count': f['page_count'], 'included_path': f['local_path']})
    public += insert('sources', ['id', 'publisher', 'url', 'resolved_url', 'retrieved_at', 'response_sha256', 'verification_note'], source_rows)
    public += insert('documents', ['id', 'external_key', 'origin', 'title', 'document_form', 'document_number', 'issued_on', 'published_at', 'issuer_organization_code', 'issuer_name', 'source_id', 'metadata_status', 'verification_note', 'source_observations'], doc_rows)
    public += insert('files', ['id', 'document_id', 'component_key', 'version_no', 'file_role', 'original_name', 'media_type', 'byte_size', 'sha256', 'page_count', 'external_url', 'local_path', 'verified_download_at'], file_rows)
    public += insert('document_classifications', ['document_id', 'work_group_code', 'classification_status', 'basis'], classification_rows)

    demo = header + '-- OPTIONAL SYNTHETIC DATA. Never use these rows as evidence of real agency work.\nBEGIN;\n'
    users, grants = [], []
    for dept, organization in scopes:
        if dept == 'vp' and organization == 'tl-hdnd':
            continue
        for prefix, role in [('cv', 'employee'), ('head', 'manager')]:
            if role == 'manager' and dept in ['tt', 'db']:
                continue
            username = 'demo_' + prefix + '_' + dept
            users.append([ident(username), username, 'GIẢ LẬP · ' + prefix + ' · ' + dept, True])
            grants.append([ident('grant:' + username), ident(username), role, organization, dept, '2025-01-01T00:00:00+07:00', 'Phân công giả lập để kiểm thử, không phải quyết định nhân sự.'])
    for username, role, organization in [('demo_clerk_ubnd', 'clerk', 'tl-ubnd'), ('demo_clerk_hdnd', 'clerk', 'tl-hdnd'), ('demo_chair', 'chair', 'tl-ubnd'), ('demo_council', 'council', 'tl-hdnd'), ('demo_admin', 'technical_admin', None), ('demo_cv_ht_02', 'employee', 'tl-ubnd')]:
        users.append([ident(username), username, 'GIẢ LẬP · ' + username, True])
        grants.append([ident('grant:' + username), ident(username), role, organization, 'ht' if username == 'demo_cv_ht_02' else None, '2025-01-01T00:00:00+07:00', 'Phân công giả lập để kiểm thử.'])
    demo += insert('users', ['id', 'username', 'display_name', 'is_demo'], users)
    demo += insert('user_roles', ['id', 'user_id', 'role_code', 'organization_code', 'department_code', 'valid_from', 'assignment_basis'], grants)
    scenarios = [('U15', 'draft'), ('U11', 'department_review'), ('U13', 'leadership_review'), ('U02', 'ready_archive'), ('H03', 'department_review'), ('H05', 'leadership_review'), ('H01', 'archived'), ('U19', 'returned')]
    demo_docs, dossiers, links, fields, classes = [], [], [], [], []
    for i, (group_code, state) in enumerate(scenarios, 1):
        g = next(g for g in groups if g['code'] == group_code)
        user = ident('demo_cv_' + g['owner']); dossier_id = ident('demo-dossier:' + str(i))
        verified = state not in ['draft', 'returned']
        dossiers.append([dossier_id, f'DEMO-2026-{i:04}', 'demo', 'GIẢ LẬP · ' + g['title'], 2026, org(g['group']), g['owner'], group_code, user, state, '2026-11-25', 'Kho mẫu · vị trí giả lập', 'Bộ hồ sơ giả lập độc lập với văn bản công khai.', user, '2026-11-10T09:00:00+07:00' if state == 'archived' else None])
        for j, t in enumerate(g['documentTypes'][:3], 1):
            doc_id = ident(f'demo-dossier:{i}:doc:{j}')
            demo_docs.append([doc_id, f'demo-document-{i}-{j}', 'demo', 'GIẢ LẬP · ' + t['name'], t['name'], 'unverified', 'verified' if verified else 'pending', user if verified else None, '2026-11-10T08:00:00+07:00' if verified else None])
            links.append([dossier_id, doc_id, j, 'internal'])
            classes.append([doc_id, group_code, t['id'], 'confirmed', 'Phân loại trong kịch bản giả lập.'])
            for pos, label in enumerate(t['fields'], 1):
                fields.append([doc_id, f"{t['id']}-F{pos:02}", 'Giá trị giả lập để kiểm thử' if verified else None, 'demo', not verified, user if verified else None, '2026-11-10T08:00:00+07:00' if verified else None])
    demo += insert('documents', ['id', 'external_key', 'origin', 'title', 'document_form', 'metadata_status', 'data_review_status', 'reviewed_by', 'reviewed_at'], demo_docs)
    demo += insert('document_classifications', ['document_id', 'work_group_code', 'document_type_code', 'classification_status', 'basis'], classes)
    demo += insert('document_field_values', ['document_id', 'field_definition_code', 'value_text', 'value_origin', 'needs_review', 'verified_by', 'verified_at'], fields)
    demo += insert('dossiers', ['id', 'code', 'origin', 'title', 'year', 'organization_code', 'department_code', 'work_group_code', 'assignee_id', 'status', 'internal_due_on', 'physical_location', 'notes', 'created_by', 'archived_at'], dossiers)
    demo += insert('dossier_documents', ['dossier_id', 'document_id', 'position', 'direction'], links)
    demo += 'COMMIT;\n'
    return {
        '002_seed_catalog.sql': catalog,
        '003_seed_public_documents.sql': public,
        '004_seed_demo_optional.sql': demo,
        'data/file_manifest.json': json.dumps(manifest, ensure_ascii=False, indent=2) + '\n',
        'data/counts.json': json.dumps({'organizations': 2, 'departments': len(departments), 'work_groups': len(groups),
            'document_types': sum(len(g['documentTypes']) for g in groups), 'field_definitions': sum(len(t['fields']) for g in groups for t in g['documentTypes']),
            'public_documents': len(records), 'source_files': len(manifest), 'included_samples': sum(bool(f['included_path']) for f in manifest),
            'demo_users': len(users), 'demo_dossiers': len(dossiers), 'demo_documents': len(demo_docs)}, ensure_ascii=False, indent=2) + '\n'
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files differ; do not write.')
    args = parser.parse_args()
    for relative, content in generate().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Out of date: ' + relative)
        else:
            path.write_text(content)
    print('Seed generation check passed.' if args.check else 'Generated catalogue, public seed, optional demo and file manifest.')
