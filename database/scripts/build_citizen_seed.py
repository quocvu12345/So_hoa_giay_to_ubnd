#!/usr/bin/env python3
"""Build the optional, idempotent citizen-sample seed; no fabricated OCR results."""
import argparse
import hashlib
import json
from pathlib import Path

from build_seeds import ident, insert

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT.parent
DATA = PROJECT / 'data/citizen-samples'


def generate():
    rows = json.loads((DATA / 'manifest.json').read_text())['documents']
    truths = json.loads((DATA / 'ground-truth.json').read_text())
    sources, documents, files, classes, links = {}, [], [], [], []
    user = ident('citizen-test-curator')
    sql = ('-- Generated by scripts/build_citizen_seed.py. OPTIONAL TEST FIXTURES.\n'
           '-- Real public forms, source-anonymized example, and explicitly synthetic scans.\n'
           '-- No OCR output or real administrative receipt is asserted. Paths are relative to database/.\n'
           '\\set ON_ERROR_STOP on\nBEGIN;\nSET search_path=hoso,pg_catalog;\n'
           'SET standard_conforming_strings=on;\n'
           "SELECT pg_advisory_xact_lock(hashtext('citizen-samples-v1'));\n")
    sql += insert('users', ['id', 'username', 'display_name', 'is_demo'],
                  [[user, 'citizen_test_curator', 'GIẢ LẬP · Người tạo bộ mẫu hồ sơ dân nộp', True]])
    cases = [('land', 'U15', 'ht', 'Chuyển nhượng, biến động đất đai'),
             ('inheritance', 'U09', 'nv', 'Thừa kế và quan hệ nhân thân'),
             ('vehicle', 'U27', 'mc', 'Chuyển nhượng xe — bộ tiếp nhận thử')]
    sql += insert('dossiers', ['id', 'code', 'origin', 'title', 'year', 'organization_code',
                              'department_code', 'work_group_code', 'status', 'notes', 'created_by'],
                  [[ident('citizen-case:' + key), 'TEST-CITIZEN-' + key.upper(), 'demo',
                    'BỘ TEST · ' + title, 2026, 'tl-ubnd', department, group, 'draft',
                    'Bộ tham khảo để thử phần mềm. Không phải hồ sơ công dân đã nộp; việc xếp nhóm không xác nhận thẩm quyền giải quyết.', user]
                   for key, group, department, title in cases])
    for position, row in enumerate(rows, 1):
        path = PROJECT / row['local_path']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == row['sha256'], path
        synthetic = row['sample_kind'].startswith('synthetic_')
        source_id = None
        if not synthetic:
            source_id = 'citizen-source-' + hashlib.sha256(row['file_url'].encode()).hexdigest()[:16]
            sources[source_id] = [source_id, row['publisher'], row['file_url'], row['resolved_url'],
                                  row['retrieved_at'], row['original_sha256'],
                                  'Hash của tệp gốc được tải; trang giới thiệu nằm trong source_observations. Không xác nhận hiệu lực hiện hành.']
        provenance = {k: row[k] for k in ['sample_kind', 'dataset', 'conversion', 'parent_document_id', 'components'] if k in row}
        if row.get('source_url'):
            provenance['source_page_url'] = row['source_url']
        if row['id'] in truths:
            provenance['test_expectation_not_ocr'] = truths[row['id']]
        documents.append([ident(row['id']), row['id'], 'demo' if synthetic else 'public_source',
                          row['title'], row['document_form'], source_id, 'needs_review', row['verification'], provenance])
        files.append([ident(row['id'] + ':pdf'), ident(row['id']), 'main', 1,
                      'scan' if synthetic else ('published_pdf' if row.get('conversion') == 'original_pdf' else 'derivative'),
                      path.name, 'application/pdf', row['byte_size'], row['sha256'], row['page_count'],
                      '../' + row['local_path'], row.get('retrieved_at') if not synthetic else None])
        if not synthetic and not row['original_path'].endswith('.pdf'):
            original = PROJECT / row['original_path']
            assert hashlib.sha256(original.read_bytes()).hexdigest() == row['original_sha256']
            files.append([ident(row['id'] + ':original'), ident(row['id']), 'original-word', 1,
                          'published_attachment', original.name,
                          'application/msword' if original.suffix == '.doc' else 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                          row['original_byte_size'], row['original_sha256'], None, '../' + row['original_path'], row['retrieved_at']])
        if row.get('expected_type_id'):
            type_id = row['expected_type_id']
            classes.append([ident(row['id']), type_id.split('-')[0], type_id, 'proposed',
                            'Nhãn bộ test theo tiêu đề form; không phải kết quả suy luận AI hay xác nhận của cán bộ.'])
            key = next(key for key, *_ in cases if row['id'].startswith('citizen-' + key))
            links.append([ident('citizen-case:' + key), ident(row['id']), position, 'reference'])
    sql += insert('sources', ['id', 'publisher', 'url', 'resolved_url', 'retrieved_at', 'response_sha256', 'verification_note'], list(sources.values()))
    sql += insert('documents', ['id', 'external_key', 'origin', 'title', 'document_form', 'source_id',
                               'metadata_status', 'verification_note', 'source_observations'], documents)
    sql += insert('files', ['id', 'document_id', 'component_key', 'version_no', 'file_role', 'original_name',
                           'media_type', 'byte_size', 'sha256', 'page_count', 'local_path', 'verified_download_at'], files)
    sql += insert('document_classifications', ['document_id', 'work_group_code', 'document_type_code', 'classification_status', 'basis'], classes)
    sql += insert('dossier_documents', ['dossier_id', 'document_id', 'position', 'relation_kind'], links)
    sql += """CREATE OR REPLACE VIEW v_citizen_samples AS
SELECT d.external_key, d.title, d.origin,
       d.source_observations->>'sample_kind' AS sample_kind,
       c.document_type_code, f.page_count, f.local_path, f.sha256, s.url AS source_url
FROM documents d JOIN files f ON f.document_id=d.id AND f.component_key='main'
LEFT JOIN document_classifications c ON c.document_id=d.id
LEFT JOIN sources s ON s.id=d.source_id
WHERE d.source_observations->>'dataset'='citizen-forms-v1';
COMMIT;
"""
    return sql


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / '007_seed_citizen_samples_optional.sql'
    output = generate()
    if args.check:
        assert target.read_text() == output, 'Citizen seed is out of date'
    else:
        target.write_text(output)
    print('Citizen seed and PDF hashes verified.' if args.check else 'Built optional citizen sample seed.')
